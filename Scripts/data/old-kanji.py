#!/usr/bin/env python3
"""Writes OldKanji+Table.swift: each old or variant kanji KANJIDIC2 links to a jōyō one.

A character outside the jōyō grades (1-8) whose variant (by JIS or UCS code) is a jōyō
character sharing an on or kun reading with it: 國 → 国, 戰 → 戦, 圖 → 図.

    Scripts/data/old-kanji.py [kanjidic2.xml(.gz) path or URL]
"""
import gzip, io, sys, urllib.request
import xml.etree.ElementTree as ET

SOURCE = "https://www.edrdg.org/kanjidic/kanjidic2.xml.gz"
OUTPUT = "Packages/YomidoriCore/Sources/YomidoriCore/Reading/OldKanji+Table.swift"


def load(source):
    if source.startswith("http"):
        data = urllib.request.urlopen(source).read()
    else:
        data = open(source, "rb").read()
    if data[:2] == b"\x1f\x8b":
        data = gzip.decompress(data)
    return ET.parse(io.BytesIO(data)).getroot()


def pairs(root):
    chars, by_code = {}, {}
    for c in root.iter("character"):
        lit = c.findtext("literal")
        grade = c.findtext("misc/grade")
        ons, kuns = set(), set()
        for r in c.iter("reading"):
            if r.get("r_type") == "ja_on":
                ons.add(r.text)
            elif r.get("r_type") == "ja_kun":
                kuns.add(r.text.split(".")[0].replace("-", ""))
        chars[lit] = dict(
            grade=int(grade) if grade else None, ons=ons, kuns=kuns,
            variants=[(v.get("var_type"), v.text) for v in c.iter("variant")])
        for cp in c.iter("cp_value"):
            by_code[(cp.get("cp_type"), cp.text)] = lit
    found = {}
    for lit, info in chars.items():
        if info["grade"] is not None and info["grade"] <= 8:
            continue
        # The compatibility ideographs normalize to their unified forms already.
        if 0xF900 <= ord(lit) <= 0xFAFF or 0x2F800 <= ord(lit) <= 0x2FA1F:
            continue
        for kind, value in info["variants"]:
            target = chr(int(value, 16)) if kind == "ucs" else by_code.get((kind, value))
            modern = chars.get(target)
            if not modern or target == lit or modern["grade"] is None or modern["grade"] > 8:
                continue
            if info["ons"] & modern["ons"] or info["kuns"] & modern["kuns"]:
                found.setdefault(lit, target)
    return sorted(found.items())


def main():
    found = pairs(load(sys.argv[1] if len(sys.argv) > 1 else SOURCE))
    flat = "".join(old + new for old, new in found)
    lines = [flat[i:i + 80] for i in range(0, len(flat), 80)]
    with open(OUTPUT, "w") as out:
        out.write("// Generated by Scripts/data/old-kanji.py from KANJIDIC2; do not edit.\n\n")
        out.write("extension OldKanji {\n")
        out.write("    /// Old and modern in pairs, one character each: 國国戰戦…\n")
        out.write("    static let pairs = \"\"\"\n")
        for index, line in enumerate(lines):
            join = "\\" if index < len(lines) - 1 else ""
            out.write(f"        {line}{join}\n")
        out.write("        \"\"\"\n}\n")
    print(f"{len(found)} pairs written to {OUTPUT}")


if __name__ == "__main__":
    main()
